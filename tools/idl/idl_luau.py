"""Luau output: the binding's generated sources (bindings/luau/lib/wire/gen/).

The IDL's names go through as they are, snake_case. Encoders are methods of the writer: each
checks its arguments as the core would, then writes one op through the buffer library, and
commits it last, so a method that errors leaves nothing behind. Names the generated code adds
can't collide with the IDL's, which are lower case and never start with `_`."""

from __future__ import annotations

from idl_model import (HANDLES, INT_LIMITS, SCALARS, Check, Field, Record, Schema, TailItem, ValueSpec, as_object,
                       optional_tails, short_header_fields, union_kind_of, user_fields)

OUT = "bindings/luau/lib/wire/gen"
BANNER = "-- Generated by tools/idl/axe_idl.py from idl/wire.idl. Do not edit; edit the IDL and\n" \
         "-- regenerate (docs/idl.md)."
KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local",
            "nil", "not", "or", "repeat", "return", "then", "true", "until", "while"}
WRITE = {"u8": "buffer.writeu8", "u16": "buffer.writeu16", "u32": "buffer.writeu32", "f32": "buffer.writef32"}
READ = {"u8": "buffer.readu8", "u16": "buffer.readu16", "u32": "buffer.readu32", "f32": "buffer.readf32"}


def key(name: str) -> str:
    """A table constructor's key: some of the IDL's names are Luau keywords (`end`)."""
    return f'["{name}"]' if name in KEYWORDS else name


def dot(obj: str, name: str) -> str:
    return f'{obj}["{name}"]' if name in KEYWORDS else f"{obj}.{name}"


def ident(name: str) -> str:
    return f"{name}_" if name in KEYWORDS else name


def doc(text: str, indent: str = "") -> list[str]:
    return [f"{indent}-- {text}"] if text else []


def files(s: Schema) -> dict[str, str]:
    return {
        f"{OUT}/ids.luau": ids_luau(s),
        f"{OUT}/commands.luau": commands_luau(s),
        f"{OUT}/events.luau": events_luau(s),
        f"{OUT}/styles.luau": styles_luau(s),
    }


def num_lit(v: float) -> str:
    return f"{v:g}" if v == int(v) else repr(v)


# ---- Enums ----------------------------------------------------------------------------------


def ids_luau(s: Schema) -> str:
    out = [BANNER, "-- The wire's enumerations (docs/command-buffer.md, docs/styles.md).", "",
           "local ids = {}", "",
           f"ids.WIRE_VERSION = {s.version}",
           f"ids.MAGIC_COMMANDS = {s.magic['commands'][0]:#x} -- \"{s.magic['commands'][1]}\"",
           f"ids.MAGIC_EVENTS = {s.magic['events'][0]:#x} -- \"{s.magic['events'][1]}\"", ""]
    for e in s.enums.values():
        out += doc(e.doc)
        out.append(f"ids.{e.name} = {{")
        for v in e.values:
            out += doc(v.doc, "  ")
            out.append(f"  {key(v.name)} = {v.value:#x}," if e.bitmask and v.value > 9 else f"  {key(v.name)} = {v.value},")
        out.append("}")
        out.append("")
        if any(v.components for v in e.values):
            table = ", ".join(f"[{v.value}] = {v.components or 0}" for v in e.values)
            out.append(f"-- Float components of a {e.name}; 0 for one this version doesn't know.")
            out.append(f"function ids.{e.name}_components(v) return ({{ {table} }})[v] or 0 end")
            out.append("")
        if any(v.min is not None for v in e.values):
            table = ", ".join(f"[{v.value}] = {v.min:g}" for v in e.values if v.min is not None)
            out.append(f"-- The smallest value of each component of a {e.name}.")
            out.append(f"function ids.{e.name}_min(v) return ({{ {table} }})[v] or -math.huge end")
            out.append("")
        if e.bitmask:
            mask = 0
            for v in e.values:
                mask |= v.value
            out.append(f"function ids.is_{e.name}(v) return v >= 0 and v <= {mask:#x} and v == math.floor(v) and bit32.band(v, {mask:#x}) == v end")
        else:
            table = ", ".join(f"[{v.value}] = true" for v in e.values)
            out.append(f"function ids.is_{e.name}(v) return ({{ {table} }})[v] == true end")
        out.append("")
    if s.style_props:
        out += doc(s.style_doc)
        out.append("ids.style_prop = {")
        out += [f"  {key(p.name)} = {p.id}," for p in s.style_props]
        out.append("}")
        out.append("")
        out.append("-- The transition of a property: 0x8000 | property.")
        out.append("function ids.transition_of(prop) return bit32.bor(0x8000, prop) end")
        out.append("")
    out.append("return ids")
    out.append("")
    return "\n".join(out)


# ---- Leaves: a fixed part flattened to scalars ---------------------------------------------


def leaves(r: Record, ref, base: int, value) -> list[tuple[int, str, str]]:
    """(offset from the record's start, scalar kind, expression) of r's fixed paRT. ref(name)
    gives a field's expression, value(record, field) what the encoder derives, or None."""
    out = []
    for f in r.fields:
        off = base + f.offset
        if f.record:
            inner = ref(f.name)
            out += leaves(f.record, lambda n, x=inner: dot(x, n), off, lambda rec, fld: None)
            continue
        v = value(r, f)
        path = v if v is not None else ref(f.name)
        st = f.type.storage or f.type.base
        if f.type.base in HANDLES:
            out.append((off, "u32", f"{path}.index"))
            out.append((off + 4, "u32", f"{path}.generation"))
        elif f.type.count > 1:
            out += [(off + SCALARS[st] * i, st, f"{path}[{i + 1}]") for i in range(f.type.count)]
        elif st == "u64":
            out.append((off, "time" if f.type.time else "u64", path))
        else:
            out.append((off, st, path))
    return out


def write_leaf(off: int, kind: str, expr: str, indent: str) -> str:
    at = f"_at + {off}"
    if kind == "u64":
        return f"{indent}RT.write_u64(_buf, {at}, {expr})"
    if kind == "time":
        return f"{indent}RT.write_time(_buf, {at}, {expr})"
    return f"{indent}{WRITE[kind]}(_buf, {at}, {expr})"


def read_leaf(off: int, kind: str) -> str:
    at = f"at + {off}"
    if kind == "u64":
        return f"RT.read_u64(b, {at})"
    if kind == "time":
        return f"RT.read_time(b, {at})"
    return f"{READ[kind]}(b, {at})"


# ---- Checks ---------------------------------------------------------------------------------


def range_conds(x: str, c: Check) -> list[str]:
    out = []
    if c.lo is not None:
        out.append(f"{x} {'>' if c.lo_open else '>='} {num_lit(c.lo)}")
    if c.hi is not None:
        out.append(f"{x} {'<' if c.hi_open else '<='} {num_lit(c.hi)}")
    return out


def finite(x: str) -> str:
    return f"math.abs({x}) < math.huge" # false for NaN


def field_conds(r: Record, f: Field, x: str, src) -> list[str]:
    conds = []
    st = f.type.storage or f.type.base
    if st in ("u8", "u16", "u32") and not f.assign and not f.reserved and f.type.count == 1:
        conds += [f"{x} >= 0", f"{x} <= {INT_LIMITS[st]:#x}", f"{x} == math.floor({x})"]
    for c in f.checks:
        if c.kind == "finite":
            conds.append(finite(x))
        elif c.kind == "whole":
            conds.append(f"{x} == math.floor({x})")
        elif c.kind == "nonzero":
            conds.append(f"{x} ~= 0")
        elif c.kind == "range":
            conds += range_conds(x, c)
        elif c.kind == "known":
            conds.append(f"IDS.is_{f.enum.name}({x})")
        elif c.kind == "components_of":
            conds.append(f"{x} ~= 0 and {x} == IDS.{r.field(c.ref).enum.name}_components({src(c.ref)})")
    return conds


def fail(name: str, what: str) -> str:
    return f'RT.bad("{name}", "{what}")'


def require(conds: list[str], name: str, what: str, indent: str) -> str:
    return f"{indent}if not ({' and '.join(conds)}) then {fail(name, what)} end"


# ---- Commands -------------------------------------------------------------------------------


def tail_expr(r: Record, t: TailItem, ref) -> str:
    v = ref(t.name)
    return f"({v} or RT.NONE)" if t.name in optional_tails(r) else v


def assigned_value(r: Record, f: Field, ref) -> str | None:
    if f.reserved:
        return "0"
    u = union_kind_of(r, f)
    if u:
        return f"{ref(u.name)}.kind"
    if f.assign == "header":
        return str(r.size)
    if f.assign == "header0":
        return f"(_full and {r.size} or 0)" if short_header_fields(r) else "0"
    if f.assign == "stride":
        return str(r.tail_item(f.assign_ref).record.size)
    if f.assign == "count":
        return f"#{tail_expr(r, r.tail_item(f.assign_ref), ref)}"
    if f.assign == "size":
        return "_size"
    if f.assign == "words":
        return "_size // 4"
    return None


def tail_bytes(r: Record, t: TailItem, ref) -> str:
    v = tail_expr(r, t, ref)
    if t.kind == "bytes":
        return f"RT.pad4(#{v})" if t.pad == 4 else f"#{v}"
    if t.kind == "array" and not t.record:
        return f"#{v} * {SCALARS[t.elem]}"
    if t.kind == "array" and not t.record.size_field:
        return f"#{v} * {t.record.size}"
    if t.kind == "array":
        return f"RT.sum({v}, R.sizeof_{t.record.name})"
    return f"R.sizeof_{t.record.name}({v})"


def write_tail(r: Record, ref) -> list[str]:
    out = []
    for t in r.tail:
        v = tail_expr(r, t, ref)
        if t.kind == "bytes":
            out.append(f"  _p = RT.write_bytes(_buf, _p, {v}, {'true' if t.pad == 4 else 'false'})")
        elif t.kind == "array" and not t.record:
            out.append(f"  _p = RT.write_{t.elem}s(_buf, _p, {v})")
        elif t.kind == "array":
            out.append(f"  for _, _x in ipairs({v}) do _p = R.write_{t.record.name}(_buf, _p, _x) end")
        elif t.kind == "single":
            out.append(f"  _p = R.write_{t.record.name}(_buf, _p, {v})")
        elif t.kind == "union":
            out.append(f"  _p = STYLES.write_value(_buf, _p, {v})")
    return out


def parallel_lines(r: Record, ref, name: str) -> list[str]:
    """Arrays sharing a count (parallel arrays) must be as long as the one it names."""
    out = []
    for f in r.fields:
        if f.assign != "count":
            continue
        first = r.tail_item(f.assign_ref)
        for t in r.tail:
            if t is not first and t.count_field == f.name:
                out.append(f"  if #{tail_expr(r, t, ref)} ~= #{tail_expr(r, first, ref)} then {fail(name, t.name)} end")
    return out


def nonzero_u32s(v: str, name: str, what: str) -> str:
    return f"  for _, _x in ipairs({v}) do if not (_x > 0 and _x <= 0xffffffff and _x == math.floor(_x)) then {fail(name, what)} end end"


def record_checks(r: Record, ref) -> list[str]:
    """What a record in a tail checks: parallel arrays, nonzero ids."""
    out = parallel_lines(r, ref, r.name)
    for t in r.tail:
        if any(c.kind == "nonzero" for c in t.checks):
            out.append(nonzero_u32s(tail_expr(r, t, ref), r.name, t.name))
    return out


def full_expr(r: Record, ref) -> str:
    """Whether a short-header record is written whole (an appended field isn't 0)."""
    terms = []
    for f in short_header_fields(r):
        terms.append(f"#{tail_expr(r, r.tail_item(f.assign_ref), ref)} ~= 0" if f.assign == "count" else f"{ref(f.name)} ~= 0")
    return " or ".join(terms)


def size_function(r: Record, ref) -> list[str]:
    base = f"({full_expr(r, ref)}) and {r.size} or {r.original}" if short_header_fields(r) else str(r.size)
    out = [f"function R.sizeof_{r.name}(v)"] + record_checks(r, ref) + [f"  local _size = {base}"]
    for t in r.tail:
        if t.kind == "union":
            out.append(f"  _size += STYLES.value_words({tail_expr(r, t, ref)}) * 4 - {r.size}")
        else:
            out.append(f"  _size += {tail_bytes(r, t, ref)}")
    out += ["  return _size", "end", ""]
    return out


def record_writer(r: Record) -> list[str]:
    def ref(n: str) -> str:
        return dot("v", n)

    out = size_function(r, ref) if r.size_field else []
    out.append(f"function R.write_{r.name}(_buf, _at, v)")
    if r.size_field:
        out.append(f"  local _size = R.sizeof_{r.name}(v)")
    lvs = leaves(r, ref, 0, lambda rec, f: assigned_value(rec, f, ref))
    if short_header_fields(r):
        out.append(f"  local _full = {full_expr(r, ref)}")
        out += [write_leaf(o, k, e, "  ") for o, k, e in lvs if o < r.original]
        out.append("  if _full then")
        out += [write_leaf(o, k, e, "    ") for o, k, e in lvs if o >= r.original]
        out.append("  end")
        out.append(f"  local _p = _at + (_full and {r.size} or {r.original})")
    else:
        out += [write_leaf(o, k, e, "  ") for o, k, e in lvs]
        out.append(f"  local _p = _at + {r.size}")
    out += write_tail(r, ref)
    out += ["  return _p", "end", ""]
    return out


def check_lines(r: Record, ref, name: str) -> list[str]:
    out = parallel_lines(r, ref, name)
    for f in user_fields(r):
        conds = field_conds(r, f, ref(f.name), ref)
        if conds:
            out.append(require(conds, name, f.name, "  "))
    for f in r.fields:
        if f.assign == "count":
            st = f.type.storage or f.type.base
            t = r.tail_item(f.assign_ref)
            n = f"#{tail_expr(r, t, ref)}"
            conds = [f"{n} <= {INT_LIMITS[st]:#x}"]
            for c in f.checks:
                if c.kind == "range":
                    conds += range_conds(n, c)
                elif c.kind == "components_of":
                    conds.append(f"{n} == IDS.{r.field(c.ref).enum.name}_components({ref(c.ref)})")
                    conds.append(f"{n} ~= 0")
            out.append(require(conds, name, f.name, "  "))
    for t in r.tail:
        v = tail_expr(r, t, ref)
        for c in t.checks:
            if c.kind == "finite":
                out.append(f"  for _, _x in ipairs({v}) do if not ({finite('_x')}) then {fail(name, t.name)} end end")
            elif c.kind == "min_of":
                e = r.field(c.ref).enum
                out.append(f"  for _, _x in ipairs({v}) do if not (_x >= IDS.{e.name}_min({ref(c.ref)})) then {fail(name, t.name)} end end")
            elif c.kind == "nonzero":
                out.append(nonzero_u32s(v, name, t.name))
            elif c.kind == "utf8":
                out.append(f"  if not RT.is_utf8({v}) then {fail(name, t.name)} end")
            elif c.kind == "no_nul":
                out.append(f'  if string.find({v}, "\\0", 1, true) then {fail(name, t.name)} end')
        if t.kind == "bytes" and t.multiple > 1:
            out.append(f"  if #{v} % {t.multiple} ~= 0 then {fail(name, t.name)} end")
        if t.kind == "array" and not t.record and t.elem == "u32" and not any(c.kind == "nonzero" for c in t.checks):
            out.append(f"  for _, _x in ipairs({v}) do if not (_x >= 0 and _x <= 0xffffffff and _x == math.floor(_x)) then {fail(name, t.name)} end end")
    return out


def command_method(r: Record) -> list[str]:
    obj = as_object(r)
    params = ["self"]
    if obj:
        params.append("fields")
    else:
        params += [ident(f.name) for f in user_fields(r)]
    params += [ident(t.name) for t in r.tail]

    def ref(n: str) -> str:
        if r.tail_item(n) or not obj:
            return ident(n)
        return dot("fields", n)

    out = [f"-- {r.name} ({r.opcode}): {r.doc}" if r.doc else f"-- {r.name} ({r.opcode})"]
    out.append(f"function Writer.{r.name}({', '.join(params)})")
    out += check_lines(r, ref, r.name)
    terms = [str(r.size)] + [tail_bytes(r, t, ref) for t in r.tail]
    out.append(f"  local _payload = {' + '.join(terms)}")
    out.append(f"  local _at = self:op({r.opcode}, _payload)")
    out.append("  local _buf = self.buf")
    out += [write_leaf(o, k, e, "  ") for o, k, e in leaves(r, ref, 0, lambda rec, f: assigned_value(rec, f, ref))]
    if r.tail:
        out.append(f"  local _p = _at + {r.size}")
        out += write_tail(r, ref)
    out += ["  self:commit(_at, _payload)", "end", ""]
    return out


def commands_luau(s: Schema) -> str:
    out = [BANNER,
           "-- The command buffer's encoder (docs/command-buffer.md): methods of the writer. Each validates",
           "-- its arguments as the core would, then appends one op; one that errors writes nothing.",
           "", 'local IDS = require("axe/wire/ids")', 'local RT = require("axe/wire/runtime")',
           'local STYLES = require("axe/wire/styles")', "", "local Writer = RT.Writer", "local R = {}", ""]
    for r in s.records.values():
        if r.name not in ("rect", "text_style"):
            out += record_writer(r)
    for r in s.commands:
        out += command_method(r)
    out.append("return Writer")
    out.append("")
    return "\n".join(out)


# ---- Events ---------------------------------------------------------------------------------


def event_value(f: Field) -> str:
    if f.record:
        inner = ", ".join(f"{key(g.name)} = {read_leaf(f.offset + g.offset, g.type.storage or g.type.base)}"
                          for g in f.record.fields)
        return f"{{ {inner} }}"
    if f.type.base in HANDLES:
        return f"{{ index = {read_leaf(f.offset, 'u32')}, generation = {read_leaf(f.offset + 4, 'u32')} }}"
    st = f.type.storage or f.type.base
    return read_leaf(f.offset, "time" if st == "u64" and f.type.time else st)


def events_luau(s: Schema) -> str:
    out = [BANNER, "-- The event buffer's decoder (docs/command-buffer.md).", "",
           'local RT = require("axe/wire/runtime")', "", "local events = {}", "",
           "-- The smallest payload of each event; a shorter one is malformed.", "events.original_size = {"]
    out += [f"  [{r.opcode}] = {r.original}," for r in s.events]
    out += ["}", "", "local decoders = {"]
    for r in s.events:
        out += doc(f"{r.name}: {r.doc}", "  ")
        fields = [f"type = {r.opcode}"] + [f"{key(f.name)} = {event_value(f)}" for f in user_fields(r)]
        out.append(f"  [{r.opcode}] = function(b, at) return {{ {', '.join(fields)} }} end,")
    out += ["}", "",
            "-- Decodes the event at byte `at` (its payload), of a known type and framed size; nil for a",
            "-- type this version doesn't know.",
            "function events.decode(b, type_, at)", "  local d = decoders[type_]", "  return d and d(b, at)", "end", "",
            "return events", ""]
    return "\n".join(out)


# ---- Style values ------------------------------------------------------------------------------


def alternatives(s: Schema, values: list[ValueSpec], smax: int) -> str:
    conds = []
    u = s.unions["style_value"]
    kinds = s.enums["value_kind"]
    for v in values:
        k = f"v.kind == {kinds.value(v.kind).value}"
        if v.kind in ("px", "percent", "number"):
            c = [k, finite("v.number")]
            if v.check:
                c += range_conds("v.number", v.check)
            if v.whole:
                c.append("v.number == math.floor(v.number)")
            conds.append("(" + " and ".join(c) + ")")
        elif v.kind == "color":
            conds.append(f"({k} and finite4(v.color))")
        elif v.kind == "keyword":
            if not v.enum:
                conds.append(f"({k} and v.keyword >= 0 and v.keyword <= 0xffffffff and v.keyword == math.floor(v.keyword))")
                continue
            e = s.enums[v.enum]
            mask = 0
            for name in (v.allowed or [x.name for x in e.values]):
                mask |= 1 << e.value(name).value
            conds.append(f"({k} and v.keyword >= 0 and v.keyword < 32 and v.keyword == math.floor(v.keyword) and "
                         f"bit32.band(bit32.rshift({mask:#x}, v.keyword), 1) == 1)")
        elif v.kind == "string":
            conds.append(f"({k} and string_ok(v.string, {v.max_bytes or smax}))")
        elif v.kind == "token":
            conds.append(f"({k} and v.token > 0 and v.token <= 0xffffffff and v.token == math.floor(v.token))")
        elif v.kind == "spring":
            c = [k]
            for f in u.variant("spring").fields:
                x = f"v.{f.name.split('.')[-1]}"
                for ch in f.checks:
                    if ch.kind == "finite":
                        c.append(finite(x))
                    elif ch.kind == "range":
                        c += range_conds(x, ch)
            conds.append("(" + " and ".join(c) + ")")
        else:
            conds.append(f"({k})")
    return " or\n      ".join(conds)


def styles_luau(s: Schema) -> str:
    u = s.unions["style_value"]
    kinds = s.enums["value_kind"]
    smax = next(int(c.hi) for c in u.variant("string").fields[0].checks if c.kind == "range" and c.hi)
    out = [BANNER, "-- Style values and what each property accepts (docs/styles.md).", "",
           'local RT = require("axe/wire/runtime")', "", "local styles = {}", "",
           f"styles.STRING_MAX = {smax}", ""]

    out.append("-- The entry's size in words, its 4-byte header included.")
    out.append("function styles.value_words(v)")
    out.append("  local k = v.kind")
    for i, v in enumerate(kinds.values):
        var = u.variant(v.name)
        head = f"  {'if' if i == 0 else 'elseif'} k == {v.value} then"
        if var and any(f.type.base == "str16" for f in var.fields):
            f = next(f for f in var.fields if f.type.base == "str16")
            out.append(f"{head} return 1 + (2 + #v.{f.name} + 3) // 4")
        else:
            size = sum(f.size for f in var.fields) if var else 0
            out.append(f"{head} return {1 + (size + 3) // 4}")
    out += ["  end", '  error("not a style value: kind " .. tostring(k), 2)', "end", ""]

    out.append("-- Writes the value at byte `at` (after its entry's header); returns the end.")
    out.append("function styles.write_value(b, at, v)")
    out.append("  local k = v.kind")
    first = True
    for v in kinds.values:
        var = u.variant(v.name)
        if not var:
            continue
        out.append(f"  {'if' if first else 'elseif'} k == {v.value} then")
        first = False
        k = 0
        for f in var.fields:
            fn = f.name.split(".")[-1]
            if f.type.base == "str16":
                out.append(f"    -- u16 length, then the bytes, zero-padded to the word")
                out.append(f"    buffer.writeu16(b, at, #v.{fn})")
                out.append(f"    return RT.write_bytes(b, at + 2, v.{fn}, true, 2)")
            elif f.type.count > 1:
                for i in range(f.type.count):
                    out.append(f"    buffer.writef32(b, at + {(k + i) * 4}, v.{fn}[{i + 1}])")
                k += f.type.count
            else:
                out.append(f"    {WRITE['f32' if f.type.base == 'f32' else 'u32']}(b, at + {k * 4}, v.{fn})")
                k += 1
        if not any(f.type.base == "str16" for f in var.fields):
            out.append(f"    return at + {k * 4}")
    out += ["  end", "  return at", "end", ""]

    string_checks = {c.kind for c in u.variant("string").fields[0].checks}
    string_conds = ["#x >= 1", "#x <= max"]
    if "no_nul" in string_checks:
        string_conds.append('not string.find(x, "\\0", 1, true)')
    if "utf8" in string_checks:
        string_conds.append("RT.is_utf8(x)")
    out += ["-- A Luau string holds any bytes, so `utf8` is checked here (docs/idl.md, \"Checks\").",
            "local function string_ok(x, max)",
            f"  return {' and '.join(string_conds)}",
            "end", "",
            "local function finite4(c)",
            "  return " + " and ".join(finite(f"c[{i}]") for i in range(1, 5)),
            "end", ""]

    trans = [p.id for p in s.style_props if "transition" in p.flags]
    decl = [p.id for p in s.style_props if p.declarable]
    out.append(f"local transition_props = {{ {', '.join(f'[{i}] = true' for i in trans)} }}")
    out.append(f"local declarable_props = {{ {', '.join(f'[{i}] = true' for i in decl)} }}")
    out += ["", "-- True for a property (or the transition of one) this version knows.",
            "function styles.prop_known(prop)",
            "  if bit32.btest(prop, 0x8000) then return transition_props[bit32.band(prop, 0x7fff)] == true end",
            "  return declarable_props[prop] == true", "end", ""]

    groups: dict[str, list] = {}
    for p in s.style_props:
        if p.declarable:
            groups.setdefault(alternatives(s, p.values, smax), []).append(p)
    out.append("local validators = {")
    for cond in groups:
        out.append(f"  function(v)\n    return {cond.replace(chr(10) + '      ', chr(10) + '      ')}\n  end,")
    out += ["}", "", "local validator_of = {"]
    for i, ps in enumerate(groups.values()):
        for p in ps:
            out.append(f"  [{p.id}] = {i + 1}, -- {p.name}")
    out += ["}", ""]

    token_cond = alternatives(s, [ValueSpec("token")], smax)
    out += ["-- True if a declaration of `prop` with this value is valid, as the core checks it.",
            "-- `override` allows unset.",
            "function styles.value_valid(prop, v, override)",
            "  if not styles.prop_known(prop) then return false end",
            f"  if v.kind == {kinds.value('unset').value} then return override == true end -- unset",
            f"  if v.kind == {kinds.value('inherit').value} or v.kind == {kinds.value('initial').value} then return true end -- inherit, initial",
            f"  if bit32.btest(prop, 0x8000) then\n    return {alternatives(s, s.transition_values, smax)}\n  end",
            f"  if v.kind == {kinds.value('token').value} then return {token_cond} end -- token",
            "  return validators[validator_of[prop]](v)", "end", "",
            "-- True if a theme token may hold this value.",
            "function styles.token_value_valid(v)",
            f"  return {alternatives(s, s.token_values, smax)}", "end", "", "return styles", ""]
    return "\n".join(out)
