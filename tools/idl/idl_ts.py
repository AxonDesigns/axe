"""TypeScript output: the @axe/wire package's generated sources (ts/packages/wire/src/gen/).

The writer packs each op's fixed part into 32-bit words through Uint32Array and Float32Array
views of one buffer, so encoding never goes through a DataView."""

from __future__ import annotations

from dataclasses import dataclass

from idl_model import HANDLES, SCALARS, Check, Enum, Field, Record, Schema, TailItem, ValueSpec

OUT = "ts/packages/wire/src/gen"
BANNER = "// Generated by tools/idl/axe_idl.py from idl/wire.idl. Do not edit; edit the IDL and\n" \
         "// regenerate (docs/idl.md).\n"
INT_MAX = {"u8": 0xFF, "u16": 0xFFFF, "u32": 0xFFFFFFFF}


def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def doc(text: str, indent: str = "") -> list[str]:
    if not text:
        return []
    return [f"{indent}/** {text.replace('*/', '* /')} */"]


def files(s: Schema) -> dict[str, str]:
    return {
        f"{OUT}/ids.ts": ids_ts(s),
        f"{OUT}/commands.ts": commands_ts(s),
        f"{OUT}/events.ts": events_ts(s),
        f"{OUT}/styles.ts": styles_ts(s),
    }


# ---- Enums ----------------------------------------------------------------------------------


def ids_ts(s: Schema) -> str:
    out = [BANNER.rstrip(), "// The wire's enumerations (docs/command-buffer.md, docs/styles.md).", "",
           f"export const WIRE_VERSION = {s.version};",
           f"export const MAGIC_COMMANDS = {s.magic['commands'][0]:#x}; // \"{s.magic['commands'][1]}\"",
           f"export const MAGIC_EVENTS = {s.magic['events'][0]:#x}; // \"{s.magic['events'][1]}\"", ""]
    for e in s.enums.values():
        name = pascal(e.name)
        out += doc(e.doc)
        out.append(f"export const {name} = {{")
        for v in e.values:
            out += doc(v.doc, "  ")
            out.append(f"  {camel(v.name)}: {v.value:#x}," if e.bitmask and v.value > 9 else f"  {camel(v.name)}: {v.value},")
        out.append("} as const;")
        out.append(f"export type {name} = (typeof {name})[keyof typeof {name}];")
        out.append("")
        if any(v.components for v in e.values):
            out.append(f"/** Float components of a {e.name}; 0 for one this version doesn't know. */")
            out.append(f"export function {camel(e.name)}Components(v: number): number {{")
            out.append("  switch (v) {")
            for v in e.values:
                out.append(f"    case {v.value}: return {v.components or 0};")
            out.append("    default: return 0;")
            out.append("  }")
            out.append("}")
            out.append("")
        if any(v.min is not None for v in e.values):
            out.append(f"/** The smallest value of each component of a {e.name}. */")
            out.append(f"export function {camel(e.name)}Min(v: number): number {{")
            out.append("  switch (v) {")
            for v in e.values:
                if v.min is not None:
                    out.append(f"    case {v.value}: return {v.min:g};")
            out.append("    default: return -Infinity;")
            out.append("  }")
            out.append("}")
            out.append("")
        if e.bitmask:
            mask = 0
            for v in e.values:
                mask |= v.value
            out.append(f"export function is{name}(v: number): boolean {{ return (v & ~{mask:#x}) === 0 && v >= 0 && v === Math.floor(v); }}")
        else:
            vals = ", ".join(str(v.value) for v in e.values)
            out.append(f"const {camel(e.name)}Values: ReadonlySet<number> = new Set([{vals}]);")
            out.append(f"export function is{name}(v: number): v is {name} {{ return {camel(e.name)}Values.has(v); }}")
        out.append("")
    if s.style_props:
        out += doc(s.style_doc)
        out.append("export const StyleProp = {")
        for p in s.style_props:
            out.append(f"  {camel(p.name)}: {p.id},")
        out.append("} as const;")
        out.append("export type StyleProp = (typeof StyleProp)[keyof typeof StyleProp];")
        out.append("export type StylePropName = keyof typeof StyleProp;")
        out.append("")
        out.append("/** The transition of a property: 0x8000 | property. */")
        out.append("export function transitionOf(prop: number): number { return 0x8000 | prop; }")
        out.append("")
    return "\n".join(out)


# ---- Leaves: a fixed part flattened to scalars ---------------------------------------------


@dataclass
class Leaf:
    offset: int        # bytes from the record's start
    kind: str          # u8, u16, u32, f32, u64, u64t (time)
    expr: str          # what is written (writer), or the destination path (reader)
    field: Field | None = None


def leaves(s: Schema, r: Record, prefix: str, base: int, values) -> list[Leaf]:
    """The scalars of r's fixed part. values(field) gives what the writer stores, or None to
    take `prefix + camel(name)`."""
    out = []
    for f in r.fields:
        off = base + f.offset
        if f.record:
            out += leaves(s, f.record, f"{prefix}{camel(f.name)}.", off, lambda x: None)
            continue
        v = values(f)
        path = v if v is not None else f"{prefix}{camel(f.name)}"
        st = f.type.storage or f.type.base
        if f.type.base in HANDLES:
            out.append(Leaf(off, "u32", f"{path}.index", f))
            out.append(Leaf(off + 4, "u32", f"{path}.generation", f))
        elif f.type.count > 1:
            for i in range(f.type.count):
                out.append(Leaf(off + SCALARS[st] * i, st, f"{path}[{i}]!", f))
        elif st == "u64":
            out.append(Leaf(off, "u64t" if f.type.time else "u64", path, f))
        else:
            out.append(Leaf(off, st, path, f))
    return out


def write_words(lvs: list[Leaf], w: str) -> list[str]:
    """Statements writing the leaves, word by word, at u32 index `w`."""
    words: dict[int, list[Leaf]] = {}
    out = []
    for lf in lvs:
        if lf.kind in ("u64", "u64t"):
            k = lf.offset // 4
            fn = "splitTime" if lf.kind == "u64t" else "splitU64"
            out.append(f"  {fn}(u32, {w} + {k}, {lf.expr});")
            continue
        words.setdefault(lf.offset // 4, []).append(lf)
    for k in sorted(words):
        parts = words[k]
        if len(parts) == 1 and parts[0].kind in ("u32", "f32") or parts[0].kind == "f32":
            arr = "f32" if parts[0].kind == "f32" else "u32"
            out.append(f"  {arr}[{w} + {k}] = {parts[0].expr};")
            continue
        terms = []
        for lf in parts:
            shift = (lf.offset % 4) * 8
            terms.append(lf.expr if shift == 0 else f"({lf.expr}) << {shift}")
        expr = " | ".join(terms)
        out.append(f"  u32[{w} + {k}] = ({expr}) >>> 0;" if len(terms) > 1 or any(lf.offset % 4 for lf in parts)
                   else f"  u32[{w} + {k}] = {expr};")
    return out


def read_leaf(lf: Leaf, w: str) -> str:
    k = lf.offset // 4
    word = f"u32[{w} + {k}]!"
    shift = (lf.offset % 4) * 8
    if lf.kind == "f32":
        return f"f32[{w} + {k}]!"
    if lf.kind == "u32":
        return word
    if lf.kind == "u64":
        return f"joinU64(u32, {w} + {k})"
    if lf.kind == "u64t":
        return f"joinTime(u32, {w} + {k})"
    mask = "0xffff" if lf.kind == "u16" else "0xff"
    if shift == 0:
        return f"{word} & {mask}"
    if shift + (16 if lf.kind == "u16" else 8) == 32:
        return f"{word} >>> {shift}"
    return f"({word} >>> {shift}) & {mask}"


# ---- Checks ---------------------------------------------------------------------------------


def num_lit(v: float) -> str:
    return f"{v:g}" if v == int(v) else repr(v)


def range_conds(x: str, c: Check) -> list[str]:
    out = []
    if c.lo is not None:
        out.append(f"{x} {'>' if c.lo_open else '>='} {num_lit(c.lo)}")
    if c.hi is not None:
        out.append(f"{x} {'<' if c.hi_open else '<='} {num_lit(c.hi)}")
    return out


def field_conds(r: Record, f: Field, x: str) -> list[str]:
    conds = []
    st = f.type.storage or f.type.base
    if st in INT_MAX and not f.assign and not f.reserved and f.type.count == 1:
        conds.append(f"isUint({x}, {INT_MAX[st]:#x})")
    for c in f.checks:
        if c.kind == "finite":
            conds.append(f"Number.isFinite({x})")
        elif c.kind == "whole":
            conds.append(f"Number.isInteger({x})")
        elif c.kind == "nonzero":
            conds.append(f"{x} !== 0")
        elif c.kind == "range":
            conds += range_conds(x, c)
        elif c.kind == "known":
            conds.append(f"is{pascal(f.enum.name)}({x})")
        elif c.kind == "components_of":
            ref = r.field(c.ref)
            conds.append(f"{x} !== 0 && {x} === {camel(ref.enum.name)}Components({camel(c.ref)})")
    return conds


# ---- Commands -------------------------------------------------------------------------------


def union_kind_of(r: Record, f: Field) -> TailItem | None:
    """The union tail item `f` selects, if f is a union's kind field: its value comes from the
    union value itself."""
    return next((t for t in r.tail if t.kind == "union" and t.count_field == f.name), None)


def user_fields(r: Record) -> list[Field]:
    return [f for f in r.fields if not f.reserved and not f.assign and not union_kind_of(r, f)]


def ts_type(s: Schema, f: Field) -> str:
    if f.record:
        return pascal(f.record.name)
    if f.type.base in HANDLES:
        return "Handle"
    if f.type.count > 1:
        return "readonly [" + ", ".join(["number"] * f.type.count) + "]"
    return "number"


def record_interface(s: Schema, r: Record, name: str | None = None) -> list[str]:
    out = doc(r.doc) + [f"export interface {name or pascal(r.name)} {{"]
    for f in user_fields(r):
        out += doc(f.doc, "  ")
        out.append(f"  readonly {camel(f.name)}: {ts_type(s, f)};")
    for t in r.tail:
        out += doc(t.doc, "  ")
        out.append(f"  readonly {camel(t.name)}: {tail_type(s, t)};")
    out.append("}")
    out.append("")
    return out


def tail_type(s: Schema, t: TailItem) -> str:
    if t.kind == "bytes":
        return "Uint8Array"
    if t.kind == "array" and not t.record:
        return "ArrayLike<number>"
    if t.kind == "array":
        return f"readonly {pascal(t.record.name)}[]"
    if t.kind == "union":
        return "StyleValue"
    return pascal(t.record.name)


def as_object(r: Record) -> bool:
    """Ops with nested records or many fields take their fixed part as one object."""
    return any(f.record for f in r.fields) or len(user_fields(r)) > 6


def assigned_value(r: Record, f: Field, src: str) -> str | None:
    if f.reserved:
        return "0"
    u = union_kind_of(r, f)
    if u:
        return f"{src}{camel(u.name)}.kind"
    if f.assign == "header":
        return str(r.size)
    if f.assign == "header0":
        return "0"
    if f.assign == "stride":
        return str(r.tail_item(f.assign_ref).record.size)
    if f.assign == "count":
        return f"{camel(f.assign_ref)}Count"
    if f.assign in ("size", "words"):
        return "size" if f.assign == "size" else "size >>> 2"
    return None


def tail_count_expr(s: Schema, t: TailItem, src: str) -> str:
    return f"{src}{camel(t.name)}.length"


def commands_ts(s: Schema) -> str:
    out = [BANNER.rstrip(),
           "// The command buffer's encoder (docs/command-buffer.md). Each method validates its",
           "// arguments as the core would, then appends one op; a method that throws writes nothing.",
           "",
           'import { type Handle, WireWriter, bad, isUint, isUtf8, splitTime, splitU64, utf8Length, encodeUtf8Into } from "../runtime.js";',
           "import * as ids from \"./ids.js\";",
           "import { type StyleValue, styleValueValid, styleTokenValueValid, styleValueWords, writeStyleValue } from \"./styles.js\";",
           "",
           "const { " + ", ".join(sorted({f"is{pascal(e.name)}" for e in s.enums.values()} |
                                         {f"{camel(e.name)}Components" for e in s.enums.values() if any(v.components for v in e.values)} |
                                         {f"{camel(e.name)}Min" for e in s.enums.values() if any(v.min is not None for v in e.values)})) + " } = ids;",
           "void utf8Length; void encodeUtf8Into; void isUtf8; void styleValueValid; void styleTokenValueValid;",
           ""]
    # Records used by ops.
    for r in s.records.values():
        if r.name == "rect":
            continue
        out += record_interface(s, r)
    for r in s.commands:
        if as_object(r):
            out += record_interface(s, Record(r.name, "record", r.fields, [], doc=f"The fixed fields of {r.name}."),
                                    pascal(r.name) + "Fields")
    out += record_writers(s)
    out.append("export class CommandWriter extends WireWriter {")
    out.append("  constructor(grow?: (current: ArrayBuffer, minBytes: number) => ArrayBuffer) {")
    out.append("    super(ids.MAGIC_COMMANDS, grow);")
    out.append("  }")
    out.append("")
    for r in s.commands:
        out += command_method(s, r)
    out.append("}")
    out.append("")
    return "\n".join(out)


def record_writers(s: Schema) -> list[str]:
    """Size and writer functions for records in tails (spans, entries, blocks)."""
    out = []
    for r in s.records.values():
        if r.name in ("rect", "text_style"):
            continue
        name = pascal(r.name)
        if r.size_field:
            out += size_function(s, r)
        out.append(f"function write{name}(w: CommandWriter, at: number, v: {name}): number {{")
        out.append("  const u32 = w.u32, f32 = w.f32;")
        out.append("  void f32;")
        if r.size_field:
            out.append(f"  const size = sizeof{name}(v);")
        out += tail_counts(s, r, "v.")
        out.append("  const word = at >> 2;")

        def vals(f, r=r):
            a = assigned_value(r, f, "v.")
            return a

        out += write_words(leaves(s, r, "v.", 0, vals), "word")
        out.append(f"  at += {r.size};")
        out += write_tail(s, r, "v.", "at")
        out.append("  return at;")
        out.append("}")
        out.append("")
    return out


def size_function(s: Schema, r: Record) -> list[str]:
    name = pascal(r.name)
    out = [f"function sizeof{name}(v: {name}): number {{", f"  let size = {r.size};"]
    for t in r.tail:
        if t.kind == "array" and t.record and t.record.size_field:
            out.append(f"  for (const x of v.{camel(t.name)}) size += sizeof{pascal(t.record.name)}(x);")
        elif t.kind == "union":
            out.append(f"  size += styleValueWords(v.{camel(t.name)}) * 4 - {r.size};")
        else:
            out.append(f"  size += {tail_bytes(s, t, 'v.')};")
    out.append("  return size;")
    out.append("}")
    out.append("")
    return out


def tail_bytes(s: Schema, t: TailItem, src: str) -> str:
    n = f"{src}{camel(t.name)}.length"
    if t.kind == "bytes":
        return f"(({n} + 3) & ~3)" if t.pad == 4 else n
    if t.kind == "array" and not t.record:
        return f"{n} * {SCALARS[t.elem]}"
    if t.kind == "array" and not t.record.size_field:
        return f"{n} * {t.record.size}"
    if t.kind == "array":
        return f"{src}{camel(t.name)}.reduce((a, x) => a + sizeof{pascal(t.record.name)}(x), 0)"
    return f"sizeof{pascal(t.record.name)}({src}{camel(t.name)})"


def tail_counts(s: Schema, r: Record, src: str) -> list[str]:
    out = []
    for f in r.fields:
        if f.assign == "count":
            out.append(f"  const {camel(f.assign_ref)}Count = {src}{camel(f.assign_ref)}.length;")
    return out


def write_tail(s: Schema, r: Record, src: str, at: str) -> list[str]:
    out = []
    for t in r.tail:
        v = f"{src}{camel(t.name)}"
        if t.kind == "bytes":
            out.append(f"  w.u8.set({v}, {at});")
            if t.pad == 4:
                out.append(f"  w.u8.fill(0, {at} + {v}.length, {at} + (({v}.length + 3) & ~3));")
                out.append(f"  {at} += ({v}.length + 3) & ~3;")
            else:
                out.append(f"  {at} += {v}.length;")
        elif t.kind == "array" and not t.record:
            arr = "f32" if t.elem == "f32" else "u32"
            out.append(f"  for (let i = 0; i < {v}.length; i++) w.{arr}[({at} >> 2) + i] = {v}[i]!;")
            out.append(f"  {at} += {v}.length * 4;")
        elif t.kind == "array":
            out.append(f"  for (const x of {v}) {at} = write{pascal(t.record.name)}(w, {at}, x);")
        elif t.kind == "single":
            out.append(f"  {at} = write{pascal(t.record.name)}(w, {at}, {v});")
        elif t.kind == "union":
            out.append(f"  {at} = writeStyleValue(w, {at}, {v});")
    return out


def check_lines(s: Schema, r: Record, src: str, name: str) -> list[str]:
    out = []
    for f in user_fields(r):
        x = f"{src}{camel(f.name)}"
        conds = field_conds(r, f, x)
        if conds:
            out.append(f"    if (!({' && '.join(conds)})) throw bad(\"{name}\", \"{f.name}\");")
    for f in r.fields:
        if f.assign == "count":
            st = f.type.storage or f.type.base
            t = r.tail_item(f.assign_ref)
            conds = [f"{camel(t.name)}.length <= {INT_MAX[st]:#x}"]
            for c in f.checks:
                if c.kind == "range":
                    conds += range_conds(f"{camel(t.name)}.length", c)
                elif c.kind == "components_of":
                    conds.append(f"{camel(t.name)}.length === {camel(r.field(c.ref).enum.name)}Components({src}{camel(c.ref)})")
                    conds.append(f"{camel(t.name)}.length !== 0")
            out.append(f"    if (!({' && '.join(conds)})) throw bad(\"{name}\", \"{f.name}\");")
    for t in r.tail:
        v = camel(t.name)
        for c in t.checks:
            if c.kind == "finite":
                out.append(f"    for (let i = 0; i < {v}.length; i++) if (!Number.isFinite({v}[i]!)) throw bad(\"{name}\", \"{t.name}\");")
            elif c.kind == "min_of":
                e = r.field(c.ref).enum
                out.append(f"    for (let i = 0; i < {v}.length; i++) if (!({v}[i]! >= {camel(e.name)}Min({src}{camel(c.ref)}))) throw bad(\"{name}\", \"{t.name}\");")
            elif c.kind == "nonzero":
                out.append(f"    for (let i = 0; i < {v}.length; i++) if (!isUint({v}[i]!, 0xffffffff) || {v}[i] === 0) throw bad(\"{name}\", \"{t.name}\");")
            elif c.kind == "utf8":
                out.append(f"    if (!isUtf8({v})) throw bad(\"{name}\", \"{t.name}\");")
            elif c.kind == "no_nul":
                out.append(f"    if ({v}.indexOf(0) >= 0) throw bad(\"{name}\", \"{t.name}\");")
        if t.kind == "bytes" and t.multiple > 1:
            out.append(f"    if ({v}.length % {t.multiple}) throw bad(\"{name}\", \"{t.name}\");")
        if t.kind == "array" and not t.record and t.elem == "u32" and not any(c.kind == "nonzero" for c in t.checks):
            out.append(f"    for (let i = 0; i < {v}.length; i++) if (!isUint({v}[i]!, 0xffffffff)) throw bad(\"{name}\", \"{t.name}\");")
    return out


def command_method(s: Schema, r: Record) -> list[str]:
    name = camel(r.name)
    obj = as_object(r)
    params = []
    if obj:
        params.append(f"fields: {pascal(r.name)}Fields")
        src = "fields."
    else:
        params += [f"{camel(f.name)}: {ts_type(s, f)}" for f in user_fields(r)]
        src = ""
    params += [f"{camel(t.name)}: {tail_type(s, t)}" for t in r.tail]
    out = [f"  /** {r.name} ({r.opcode}): {r.doc.replace('*/', '* /')} */"]
    out.append(f"  {name}({', '.join(params)}): void {{")
    out += check_lines(s, r, src, r.name)
    out += ["  " + line for line in tail_counts(s, r, "")]
    # Payload size.
    terms = [str(r.size)] + [tail_bytes(s, t, "") for t in r.tail]
    out.append(f"    const payload = {' + '.join(terms)};")
    out.append(f"    let at = this.op({r.opcode}, payload);")
    out.append("    const u32 = this.u32, f32 = this.f32;")
    out.append("    void f32;")
    out.append("    const word = at >> 2;")

    def vals(f, r=r):
        return assigned_value(r, f, src)

    out += ["  " + line for line in write_words(leaves(s, r, src, 0, vals), "word")]
    if r.tail:
        out.append(f"    at += {r.size};")
        out += ["  " + line.replace("w.", "this.").replace("(w, ", "(this, ") for line in write_tail(s, r, "", "at")]
    out.append("    void at;")
    out.append("  }")
    out.append("")
    return out


# ---- Events ---------------------------------------------------------------------------------


def events_ts(s: Schema) -> str:
    out = [BANNER.rstrip(), "// The event buffer's decoder (docs/command-buffer.md).", "",
           'import { type Handle, joinTime, joinU64 } from "../runtime.js";',
           'import { EventType } from "./ids.js";', "",
           "/** A rectangle in logical pixels. */",
           "export interface Rect { readonly x: number; readonly y: number; readonly width: number; readonly height: number; }",
           ""]
    names = []
    for r in s.events:
        n = pascal(r.name) + "Event"
        names.append(n)
        out += doc(f"{r.name} ({r.opcode}): {r.doc}")
        out.append(f"export interface {n} {{")
        out.append(f"  readonly type: typeof EventType.{camel(r.name)};")
        for f in user_fields(r):
            t = "Rect" if f.record else ts_type(s, f)
            note = " /** animation-clock ns (rounded above 2^53) */" if f.type.time else ""
            out.append(f"  readonly {camel(f.name)}: {t};{note}")
        out.append("}")
        out.append("")
    out.append(f"export type WireEvent = {' | '.join(names)};")
    out.append("")
    out.append(f"/** The smallest payload of each event; a shorter one is malformed. */")
    out.append("export function eventOriginalSize(type: number): number {")
    out.append("  switch (type) {")
    for r in s.events:
        out.append(f"    case {r.opcode}: return {r.original};")
    out.append("    default: return 0;")
    out.append("  }")
    out.append("}")
    out.append("")
    out.append("/** Decodes the event at byte `at` (its payload, 4-aligned), of a known type and framed")
    out.append(" * size; null for a type this version doesn't know. */")
    out.append("export function decodeEvent(u32: Uint32Array, f32: Float32Array, type: number, at: number): WireEvent | null {")
    out.append("  const w = at >> 2;")
    out.append("  void f32;")
    out.append("  switch (type) {")
    for r in s.events:
        out.append(f"    case {r.opcode}:")
        props = [f"type: {r.opcode}"]
        for f in user_fields(r):
            if f.record:
                inner = leaves(s, f.record, "", f.offset, lambda x: None)
                fields = ", ".join(f"{camel(lf.field.name)}: {read_leaf(lf, 'w')}" for lf in inner)
                props.append(f"{camel(f.name)}: {{ {fields} }}")
            elif f.type.base in HANDLES:
                k = f.offset // 4
                props.append(f"{camel(f.name)}: {{ index: u32[w + {k}]!, generation: u32[w + {k + 1}]! }}")
            else:
                lf = leaves(s, Record("x", "record", [f], []), "", 0, lambda x: None)[0]
                props.append(f"{camel(f.name)}: {read_leaf(lf, 'w')}")
        out.append(f"      return {{ {', '.join(props)} }};")
    out.append("    default:")
    out.append("      return null;")
    out.append("  }")
    out.append("}")
    out.append("")
    return "\n".join(out)


# ---- Style values ------------------------------------------------------------------------------


def styles_ts(s: Schema) -> str:
    u = s.unions["style_value"]
    kinds = s.enums["value_kind"]
    smax = next(int(c.hi) for c in u.variant("string").fields[0].checks if c.kind == "range" and c.hi)
    out = [BANNER.rstrip(), "// Style values and what each property accepts (docs/styles.md).", "",
           'import { type WireWriter, encodeUtf8Into, utf8Length } from "../runtime.js";',
           'import { StyleProp, ValueKind } from "./ids.js";', "",
           f"export const STYLE_STRING_MAX = {smax};", ""]
    value_types = []
    for v in kinds.values:
        tn = pascal(v.name) + "Value"
        value_types.append(tn)
        var = u.variant(v.name)
        fields = [f"readonly kind: typeof ValueKind.{camel(v.name)}"]
        for f in (var.fields if var else []):
            fn = camel(f.name.split(".")[-1])
            if f.type.base == "str16":
                fields.append(f"readonly {fn}: string")
            elif f.type.count > 1:
                fields.append(f"readonly {fn}: readonly [" + ", ".join(["number"] * f.type.count) + "]")
            else:
                fields.append(f"readonly {fn}: number")
        out += doc(v.doc)
        out.append(f"export interface {tn} {{ {'; '.join(fields)} }}")
    out.append(f"export type StyleValue = {' | '.join(value_types)};")
    out.append("")

    # Words.
    out.append("/** The entry's size in words, its 4-byte header included. */")
    out.append("export function styleValueWords(v: StyleValue): number {")
    out.append("  switch (v.kind) {")
    for v in kinds.values:
        var = u.variant(v.name)
        if var and any(f.type.base == "str16" for f in var.fields):
            f = next(f for f in var.fields if f.type.base == "str16")
            out.append(f"    case {v.value}: return 1 + ((2 + utf8Length(v.{camel(f.name)}) + 3) >> 2);")
        else:
            size = sum(f.size for f in var.fields) if var else 0
            out.append(f"    case {v.value}: return {1 + (size + 3) // 4};")
    out.append("  }")
    out.append("}")
    out.append("")

    # Writing the value after the entry header (the entry writer wrote the header).
    out.append("/** Writes the value at byte `at` (after its entry's header); returns the end. */")
    out.append("export function writeStyleValue(w: WireWriter, at: number, v: StyleValue): number {")
    out.append("  const word = at >> 2;")
    out.append("  void word;")
    out.append("  switch (v.kind) {")
    for v in kinds.values:
        var = u.variant(v.name)
        out.append(f"    case {v.value}:")
        if not var:
            out.append("      return at;")
            continue
        k = 0
        for f in var.fields:
            fn = camel(f.name.split(".")[-1])
            if f.type.base == "str16":
                out.append(f"      {{")
                out.append(f"        // u16 length, then the bytes, zero-padded to the word")
                out.append(f"        const n = encodeUtf8Into(v.{fn}, w.u8, at + 2);")
                out.append(f"        const end = at + ((2 + n + 3) & ~3);")
                out.append(f"        w.u8[at] = n & 0xff;")
                out.append(f"        w.u8[at + 1] = n >>> 8;")
                out.append(f"        w.u8.fill(0, at + 2 + n, end);")
                out.append(f"        return end;")
                out.append(f"      }}")
            elif f.type.count > 1:
                for i in range(f.type.count):
                    out.append(f"      w.f32[word + {k + i}] = v.{fn}[{i}];")
                k += f.type.count
            else:
                arr = "f32" if f.type.base == "f32" else "u32"
                out.append(f"      w.{arr}[word + {k}] = v.{fn};")
                k += 1
        if not any(f.type.base == "str16" for f in var.fields):
            out.append(f"      return at + {k * 4};")
    out.append("  }")
    out.append("}")
    out.append("")

    # Validation, as the core checks it.
    out.append("function stringOk(s: string, max: number): boolean {")
    out.append("  const n = utf8Length(s);")
    out.append("  return n >= 1 && n <= max && s.indexOf(\"\\0\") < 0;")
    out.append("}")
    out.append("")
    out.append("function finite4(c: readonly number[]): boolean {")
    out.append("  return Number.isFinite(c[0]) && Number.isFinite(c[1]) && Number.isFinite(c[2]) && Number.isFinite(c[3]);")
    out.append("}")
    out.append("")
    out.append("/** True for a property (or the transition of one) this version knows. */")
    out.append("export function stylePropKnown(prop: number): boolean {")
    trans = [str(p.id) for p in s.style_props if "transition" in p.flags]
    decl = [str(p.id) for p in s.style_props if p.declarable]
    out.append(f"  if (prop & 0x8000) return transitionProps.has(prop & 0x7fff);")
    out.append(f"  return declarableProps.has(prop);")
    out.append("}")
    out.append(f"const transitionProps: ReadonlySet<number> = new Set([{', '.join(trans)}]);")
    out.append(f"const declarableProps: ReadonlySet<number> = new Set([{', '.join(decl)}]);")
    out.append("")
    out.append("/** True if a declaration of `prop` with this value is valid, as the core checks it.")
    out.append(" * `override` allows unset. */")
    out.append("export function styleValueValid(prop: number, v: StyleValue, override: boolean): boolean {")
    out.append("  if (!stylePropKnown(prop)) return false;")
    out.append(f"  if (v.kind === ValueKind.unset) return override;")
    out.append(f"  if (v.kind === ValueKind.inherit || v.kind === ValueKind.initial) return true;")
    out.append(f"  if (prop & 0x8000) return {ts_alternatives(s, s.transition_values, smax)};")
    out.append(f"  if (v.kind === ValueKind.token) return v.token !== 0 && v.token === (v.token >>> 0);")
    out.append("  switch (prop) {")
    groups: dict[str, list[int]] = {}
    for p in s.style_props:
        if p.declarable:
            groups.setdefault(ts_alternatives(s, p.values, smax), []).append(p.name)
    for cond, names in groups.items():
        for n in names:
            out.append(f"    case StyleProp.{camel(n)}:")
        out.append(f"      return {cond};")
    out.append("    default:")
    out.append("      return false;")
    out.append("  }")
    out.append("}")
    out.append("")
    out.append("/** True if a theme token may hold this value. */")
    out.append("export function styleTokenValueValid(v: StyleValue): boolean {")
    out.append(f"  return {ts_alternatives(s, s.token_values, smax)};")
    out.append("}")
    out.append("")
    # Per-property value types.
    out.append("/** The values each property takes (token references, inherit and initial aside). */")
    out.append("export interface StylePropValues {")
    for p in s.style_props:
        if not p.declarable:
            continue
        kinds_used = []
        for v in p.values:
            t = pascal(v.kind) + "Value"
            if t not in kinds_used:
                kinds_used.append(t)
        out.append(f"  {camel(p.name)}: {' | '.join(kinds_used)};")
    out.append("}")
    out.append("")
    out.append("/** The properties that have a transition. */")
    out.append("export type TransitionPropName = " + " | ".join(f'"{camel(p.name)}"' for p in s.style_props if "transition" in p.flags) + ";")
    out.append("")
    out.append("/** Properties whose computed value children inherit. */")
    out.append("export const inheritedProps: ReadonlySet<number> = new Set([" +
               ", ".join(str(p.id) for p in s.style_props if "inherited" in p.flags) + "]);")
    out.append("")
    return "\n".join(out)


def ts_alternatives(s: Schema, values: list[ValueSpec], smax: int) -> str:
    conds = []
    u = s.unions["style_value"]
    for v in values:
        k = f"v.kind === ValueKind.{camel(v.kind)}"
        if v.kind in ("px", "percent", "number"):
            c = [k, "Number.isFinite(v.number)"]
            if v.check:
                c += range_conds("v.number", v.check)
            if v.whole:
                c.append("Number.isInteger(v.number)")
            conds.append("(" + " && ".join(c) + ")")
        elif v.kind == "color":
            conds.append(f"({k} && finite4(v.color))")
        elif v.kind == "keyword":
            if not v.enum:
                conds.append(f"({k} && v.keyword === (v.keyword >>> 0))")
                continue
            e = s.enums[v.enum]
            mask = 0
            for name in (v.allowed or [x.name for x in e.values]):
                mask |= 1 << e.value(name).value
            conds.append(f"({k} && v.keyword >= 0 && v.keyword < 32 && Number.isInteger(v.keyword) && (({mask:#x} >>> v.keyword) & 1) === 1)")
        elif v.kind == "string":
            conds.append(f"({k} && stringOk(v.string, {v.max_bytes or smax}))")
        elif v.kind == "token":
            conds.append(f"({k} && v.token !== 0 && v.token === (v.token >>> 0))")
        elif v.kind == "spring":
            var = u.variant("spring")
            c = [k]
            for f in var.fields:
                x = f"v.{camel(f.name.split('.')[-1])}"
                for ch in f.checks:
                    if ch.kind == "finite":
                        c.append(f"Number.isFinite({x})")
                    elif ch.kind == "range":
                        c += range_conds(x, ch)
            conds.append("(" + " && ".join(c) + ")")
        else:
            conds.append(f"({k})")
    return " ||\n        ".join(conds)
