"""C output: the public enums (include/ui/wire_ids.h) and the codec used by the writer, the
scene and the event reader (src/wire/gen/wire_gen.{h,c})."""

from __future__ import annotations

import textwrap

from idl_model import HANDLES, SCALARS, Check, Enum, Field, Record, Schema, TailItem, ValueSpec

BANNER = "// Generated by tools/idl/axe_idl.py from idl/wire.idl. Do not edit; edit the IDL and\n" \
         "// regenerate (docs/idl.md).\n"
CTYPES = {"u8": "uint8_t", "u16": "uint16_t", "u32": "uint32_t", "u64": "uint64_t", "f32": "float"}
WIDTH = 100


def comment(text: str, indent: str = "", width: int = WIDTH) -> list[str]:
    if not text:
        return []
    return [indent + "// " + line for line in
            textwrap.wrap(text, width - len(indent) - 3, break_on_hyphens=False)]


def upper(name: str) -> str:
    return name.upper()


def cname(r: Record) -> str:
    return f"ui_wire_{r.name}"


def const(r: Record, what: str) -> str:
    return f"UI_WIRE_{upper(r.name)}_{what}"


def num(v: float) -> str:
    """A float literal for C."""
    if v == int(v) and abs(v) < 1e15:
        return f"{int(v)}.0f" if v else "0.0f"
    return f"{v!r}f"


def field_ctype(f: Field) -> str:
    if f.record:
        return f"ui_wire_{f.record.name}"
    if f.type.base in HANDLES:
        return "ui_handle"
    return CTYPES[f.type.storage or f.type.base]


def enum_const(e: Enum, value: str) -> str:
    v = e.value(value)
    if e.c_type:
        return f"{e.c_prefix}{upper(v.name)}"
    return f"UI_WIRE_{upper(e.name)}_{upper(v.name)}"


# ---- Public enums ---------------------------------------------------------------------------


def wire_ids_h(s: Schema) -> str:
    out = [BANNER.rstrip(), "// The wire's enumerations: opcodes, properties, keywords and states "
           "(docs/command-buffer.md,", "// docs/styles.md). Included by ui/wire.h.", "#pragma once", "",
           "#include <stdint.h>", "", "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
           f"#define UI_WIRE_VERSION {s.version}u", ""]
    for e in s.enums.values():
        if not e.c_type:
            continue
        out += comment(e.doc)
        out.append(f"typedef enum {e.c_type} {{")
        width = max(len(f"{e.c_prefix}{upper(v.name)} = {v.value:#x}" if e.bitmask else
                        f"{e.c_prefix}{upper(v.name)} = {v.value}") for v in e.values) + 1
        for v in e.values:
            lit = f"{v.value:#x}u" if e.bitmask and v.value > 9 else (f"{v.value}u" if e.bitmask else str(v.value))
            item = f"    {e.c_prefix}{upper(v.name)} = {lit},"
            doc = v.doc
            if v.components:
                doc = (f"{v.components} component{'s' if v.components > 1 else ''}" +
                       (f"; {doc}" if doc else ""))
            out += with_comment(item, doc, width + 6)
        out.append(f"}} {e.c_type};")
        out.append("")
        if any(v.components for v in e.values):
            most = max(v.components or 0 for v in e.values)
            out.append(f"#define {e.c_prefix}MAX_COMPONENTS {most}u")
            out.append("")
            out += comment(f"Number of float components of a {e.name}, or 0 if it is unknown.")
            out.append(f"uint32_t {e.c_type}_components({e.c_type} {e.name});")
            out.append("")
    if s.style_props:
        c_type, prefix = s.style_c
        out += comment(s.style_doc)
        out.append(f"typedef enum {c_type} {{")
        for p in s.style_props:
            if p.section:
                out += comment(p.section, "    ")
            doc = render_values(p.values) if p.declarable else ""
            flags = sorted(p.flags - {"layout", "shaping", "transition"})
            parts = [x for x in (doc, ", ".join(flags), p.doc) if x]
            out += with_comment(f"    {prefix}{upper(p.name)} = {p.id},", "; ".join(parts), 0)
        out.append(f"}} {c_type};")
        out.append("")
        out += comment("The transition of a property: a spring that animates the property's value "
                       "whenever what it resolves to changes, whatever the reason. Its value is "
                       "UI_VALUE_SPRING, or UI_VALUE_NONE for no transition. Transitions exist for " +
                       ", ".join(p.name for p in s.style_props if "transition" in p.flags) + ".")
        out.append(f"#define {prefix}TRANSITION(prop) ((uint16_t)(0x8000u | (uint16_t)(prop)))")
        out.append("")
        smax = string_max(s)
        out.append(f"#define {prefix}STRING_MAX {smax}u // what fits an entry of 255 words")
        out.append("")
    out += ["#ifdef __cplusplus", "}", "#endif", ""]
    return "\n".join(out)


def with_comment(item: str, doc: str, pad: int) -> list[str]:
    """An enumerator with its doc as a trailing comment, or above it when that would be too long."""
    if not doc:
        return [item]
    line = item.ljust(pad) + f" // {doc}"
    if len(line) <= WIDTH:
        return [line]
    indent = item[:len(item) - len(item.lstrip())]
    return comment(doc, indent) + [item]


def render_values(values: list[ValueSpec]) -> str:
    out = []
    for v in values:
        t = v.kind
        if v.kind == "keyword":
            t = f"keyword {v.enum}" + (f" ({' '.join(v.allowed)})" if v.allowed else "")
        if v.check:
            t += " " + render_range(v.check)
        if v.whole:
            t += " whole"
        if v.max_bytes:
            t += f" <= {v.max_bytes} bytes"
        out.append(t)
    return " | ".join(out)


def render_range(c: Check) -> str:
    if c.lo is not None and c.hi is not None:
        return f"in {'(' if c.lo_open else '['}{c.lo:g}, {c.hi:g}{')' if c.hi_open else ']'}"
    if c.lo is not None:
        return f"{'>' if c.lo_open else '>='} {c.lo:g}"
    return f"{'<' if c.hi_open else '<='} {c.hi:g}"


def string_max(s: Schema) -> int:
    u = s.unions["style_value"]
    v = u.variant("string")
    for c in v.fields[0].checks:
        if c.kind == "range" and c.hi is not None:
            return int(c.hi)
    return 0xFFFF


