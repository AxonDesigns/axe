def gen_h(s: Schema) -> str:
    out = [BANNER.rstrip(),
           "// The codec of every op, event and record: fixed parts as structs with readers and",
           "// writers, where the variable data sits, encoders, framing and value checks.",
           "// docs/command-buffer.md describes the format; docs/idl.md how this is generated.",
           "#pragma once", "", "#include <stdbool.h>", "#include <stddef.h>", "#include <stdint.h>", "",
           '#include "wire/wire.h"', "",
           f"#define UI_WIRE_MAGIC_CMD {s.magic['commands'][0]:#010x}u   // \"{s.magic['commands'][1]}\"",
           f"#define UI_WIRE_MAGIC_EVENT {s.magic['events'][0]:#010x}u // \"{s.magic['events'][1]}\"", ""]
    for e in s.enums.values():
        if e.c_type:
            continue
        out += comment(e.doc)
        out.append("enum {")
        for v in e.values:
            out.append(f"    UI_WIRE_{upper(e.name)}_{upper(v.name)} = {v.value:#x}," +
                       (f" // {v.doc}" if v.doc else ""))
        out.append("};")
        out.append("")
    for r in list(s.records.values()) + s.messages():
        out += record_decls(s, r)
    out += style_decls(s)
    out += ["// Checks the framing of every op of a command buffer without applying anything: the",
            "// header, then each known op's fixed part, sizes and variable data. Unknown ops are",
            "// skipped. UI_OK or UI_ERR_MALFORMED.",
            "ui_result ui_wire_validate_commands(const uint8_t *data, size_t size);",
            "// The framing of one op or event: false if its payload can't hold what it describes.",
            "bool ui_wire_command_framed(uint16_t opcode, const uint8_t *payload, uint32_t size);",
            "bool ui_wire_event_framed(uint16_t type, const uint8_t *payload, uint32_t size);", ""]
    return "\n".join(out)


def struct_fields(r: Record) -> list[str]:
    lines = []
    for f in r.fields:
        if f.reserved:
            continue
        arr = f"[{f.type.count}]" if f.type.count > 1 else ""
        doc = f.doc
        if f.type.time:
            doc = ("animation-clock ns" + (f"; {doc}" if doc else ""))
        lines.append(f"    {field_ctype(f)} {f.name}{arr};" + (f" // {doc}" if doc else ""))
    return lines


def record_decls(s: Schema, r: Record) -> list[str]:
    n = cname(r)
    out = [f"// ---- {r.name} " + "-" * max(4, 88 - len(r.name))]
    if r.kind != "record":
        out += comment(f"{r.kind} {r.opcode}: {strip_md(r.doc)}" if r.doc else f"{r.kind} {r.opcode}")
    else:
        out += comment(r.doc)
    out.append(f"typedef struct {n} {{")
    out += struct_fields(r) or ["    uint8_t unused_;"]
    out.append(f"}} {n};")
    out.append(f"enum {{ {const(r, 'ORIGINAL')} = {r.original}, {const(r, 'SIZE')} = {r.size} }};")
    sent = "sent" if r.size > r.original else "sent_unused"
    out.append(f"// Reads the fixed part from the first `sent` bytes (at least the original size):")
    out.append(f"// fields an older writer didn't send read as 0, fields a newer one appended are skipped.")
    out.append(f"static inline void {n}_read(const uint8_t *p, uint32_t {sent}, {n} *o) {{")
    if r.size > r.original:
        out.append(f"    uint8_t full[{const(r, 'SIZE')}];")
        out.append(f"    if (sent < sizeof full) {{")
        out.append(f"        ui_wire_read_fields(full, sizeof full, p, sent);")
        out.append(f"        p = full;")
        out.append(f"    }}")
    else:
        out.append(f"    (void){sent};")
    for f in r.fields:
        if f.reserved:
            continue
        out += read_field(f, "p", "o->")
    out.append("}")
    out.append(f"// Writes the fixed part ({const(r, 'SIZE')} bytes) and returns the end. Header and record")
    out.append(f"// sizes are this version's; counts and lengths are the caller's.")
    out.append(f"static inline uint8_t *{n}_write(uint8_t *p, const {n} *v) {{")
    for f in r.fields:
        out += write_field(s, r, f)
    out.append(f"    return p + {const(r, 'SIZE')};")
    out.append("}")
    hf = r.header_field
    if hf:
        orig = const(r, "ORIGINAL")
        out.append(f"// Where the variable data starts: the header size it carries (0 stands for the original).")
        out.append(f"static inline uint32_t {n}_header_size(const uint8_t *p) {{")
        out.append(f"    uint32_t n = {get_expr(hf, 'p')};")
        out.append(f"    return n ? n : {orig};")
        out.append("}")
    sf = r.size_field
    if sf:
        mult = " * 4u" if sf.assign == "words" else ""
        out.append(f"// The record's size in bytes, from its size field.")
        out.append(f"static inline uint32_t {n}_size(const uint8_t *p) {{ return (uint32_t){get_expr(sf, 'p')}{mult}; }}")
    for f in r.fields:
        if f.assign == "stride":
            rec = r.tail_item(f.assign_ref).record
            out.append(f"// The size of each `{f.assign_ref}` record (0 stands for the original {rec.original}).")
            out.append(f"static inline uint32_t {n}_{f.assign_ref}_stride(const uint8_t *p) {{")
            out.append(f"    uint32_t n = {get_expr(f, 'p')};")
            out.append(f"    return n ? n : {const(rec, 'ORIGINAL')};")
            out.append("}")
    if r.tail:
        out += tail_decls(s, r)
    if r.kind == "command" and has_checks(r):
        out += comment("NULL when the op's values are in range, else the name of the first field that "
                       "isn't (drops in the core, refusals in writers)." +
                       check_args_doc(r))
        out.append(f"const char *{n}_check(const {n} *v{check_params(r)});")
    if r.kind in ("command", "event"):
        out += put_decl(s, r)
    out.append("")
    return out


def strip_md(text: str) -> str:
    return text.replace("`", "")


def get_expr(f: Field, p: str, off: int | None = None) -> str:
    o = f.offset if off is None else off
    st = f.type.storage or f.type.base
    if f.type.base in HANDLES:
        return f"ui_wire_get_handle({p} + {o})"
    if st == "u8":
        return f"{p}[{o}]"
    return f"ui_wire_get_{st}({p} + {o})"


def read_field(f: Field, p: str, dst: str, off0: int = 0) -> list[str]:
    off = f.offset + off0
    if f.record:
        return [f"    ui_wire_{f.record.name}_read({p} + {off}, {const(f.record, 'SIZE')}, &{dst}{f.name});"]
    if f.type.count > 1:
        return [f"    for (int i = 0; i < {f.type.count}; i++) {dst}{f.name}[i] = "
                f"ui_wire_get_{f.type.base}({p} + {off} + {SCALARS[f.type.base]} * i);"]
    return [f"    {dst}{f.name} = {get_expr(f, p, off)};"]


def write_value(s: Schema, r: Record, f: Field) -> str:
    """What the writer stores in field f."""
    if f.reserved:
        return "0"
    if f.assign == "header":
        return const(r, "SIZE")
    if f.assign == "header0":
        return "0"
    if f.assign == "stride":
        return const(r.tail_item(f.assign_ref).record, "SIZE")
    return f"v->{f.name}"


def write_field(s: Schema, r: Record, f: Field) -> list[str]:
    off = f.offset
    val = write_value(s, r, f)
    if f.record:
        return [f"    ui_wire_{f.record.name}_write(p + {off}, &v->{f.name});"]
    if f.type.count > 1:
        return [f"    for (int i = 0; i < {f.type.count}; i++) ui_wire_put_{f.type.base}(p + {off} + "
                f"{SCALARS[f.type.base]} * i, v->{f.name}[i]);"]
    if f.type.base in HANDLES:
        return [f"    ui_wire_put_handle(p + {off}, {val});"]
    st = f.type.storage or f.type.base
    if st == "u8":
        return [f"    p[{off}] = (uint8_t){val};" if val != "0" else f"    p[{off}] = 0;"]
    cast = f"({CTYPES[st]})" if val.startswith("UI_") or val == "0" else ""
    return [f"    ui_wire_put_{st}(p + {off}, {cast}{val});"]


def tail_decls(s: Schema, r: Record) -> list[str]:
    n = cname(r)
    out = [f"// Where the variable data of a framed {r.name} sits."]
    out.append(f"typedef struct {n}_tail {{")
    for ti in r.tail:
        doc = ti.doc or {"array": f"{ti.count_field} {ti.elem} records" if ti.record else f"{ti.count_field} {ti.elem}",
                         "bytes": f"{ti.count_field} bytes"}.get(ti.kind, ti.elem)
        out.append(f"    const uint8_t *{ti.name}; // {doc}")
        if stride_field(r, ti):
            out.append(f"    uint32_t {ti.name}_stride;")
    out.append(f"}} {n}_tail;")
    out.append(f"static inline void {n}_tail_of(const uint8_t *p, const {n} *h, {n}_tail *t) {{")
    start = f"{n}_header_size(p)" if r.header_field else const(r, "ORIGINAL")
    out.append(f"    uint32_t off = {start};")
    for i, ti in enumerate(r.tail):
        out.append(f"    t->{ti.name} = p + off;")
        last = i == len(r.tail) - 1
        step = tail_step(s, r, ti, "h->", f"t->{ti.name}_stride" if stride_field(r, ti) else None)
        if stride_field(r, ti):
            out.append(f"    t->{ti.name}_stride = {n}_{ti.name}_stride(p);")
        if not last and step:
            out.append(f"    off += {step};")
    out.append("    (void)h;")
    out.append("}")
    for ti in r.tail:
        if ti.kind == "array" and not ti.record:
            ct = CTYPES[ti.elem]
            out.append(f"// Element i of `{ti.name}`.")
            out.append(f"static inline {ct} {n}_{ti.name}_at(const {n}_tail *t, uint32_t i) {{")
            out.append(f"    return ui_wire_get_{ti.elem}(t->{ti.name} + {SCALARS[ti.elem]}u * i);")
            out.append("}")
    return out


def stride_field(r: Record, ti: TailItem) -> Field | None:
    return next((f for f in r.fields if f.assign == "stride" and f.assign_ref == ti.name), None)


def tail_step(s: Schema, r: Record, ti: TailItem, h: str, stride: str | None) -> str:
    """Bytes of a tail item, as a C expression (for items that aren't self-sized)."""
    if ti.kind == "bytes":
        cnt = f"{h}{ti.count_field}"
        return f"ui_wire_pad4({cnt})" if ti.pad == 4 else (f"(({cnt} + 1u) & ~1u)" if ti.pad == 2 else cnt)
    if ti.kind == "array":
        if ti.record and ti.record.size_field:
            return ""
        size = stride or (const(ti.record, "SIZE") if ti.record else str(SCALARS[ti.elem]))
        return f"{size} * (uint32_t){h}{ti.count_field}"
    return ""


def has_checks(r: Record) -> bool:
    return any(f.checks for f in r.fields) or any(t.checks for t in r.tail)


def check_tails(r: Record) -> list[TailItem]:
    return [t for t in r.tail if t.checks]


def check_params(r: Record) -> str:
    out = ""
    for t in check_tails(r):
        if t.kind == "bytes":
            out += f", const void *{t.name}"
        else:
            out += f", const {CTYPES[t.elem]} *{t.name}"
    return out


def check_args_doc(r: Record) -> str:
    ts = check_tails(r)
    if not ts:
        return ""
    return " " + "; ".join(f"`{t.name}`: the decoded {t.name} ({t.count_field} of them)" for t in ts) + "."


def put_params(s: Schema, r: Record) -> str:
    out = ""
    for ti in r.tail:
        if ti.kind == "bytes":
            out += f", const void *{ti.name}"
        elif ti.kind == "array" and ti.record and not ti.record.size_field:
            out += f", const ui_wire_{ti.record.name} *{ti.name}"
        elif ti.kind == "array" and not ti.record:
            out += f", const {CTYPES[ti.elem]} *{ti.name}"
        else:
            out += f", uint32_t {ti.name}_bytes, uint8_t **{ti.name}"
    return out


def put_decl(s: Schema, r: Record) -> list[str]:
    n = cname(r)
    doc = (f"Appends a {r.name} {'op' if r.kind == 'command' else 'event'}. Counts and lengths in *v must "
           "describe the data passed; padding is zeroed.")
    if any(t.kind in ("single",) or (t.record and t.record.size_field) for t in r.tail):
        doc += (" Self-sized data (`<name>_bytes`, a multiple of 4) is reserved, and *<name> points "
                "where the caller writes it.")
    doc += " UI_ERR_INVALID_ARGUMENT if the op would be too large, UI_ERR_OUT_OF_MEMORY."
    return comment(doc) + [f"ui_result {n}_put(ui_wire_buf *b, const {n} *v{put_params(s, r)});"]


def style_decls(s: Schema) -> list[str]:
    if not s.style_props:
        return []
    return [
        "// ---- Style values " + "-" * 82,
        "// The smallest entry (in words, header included) of a value kind; 0 for a kind this",
        "// version doesn't know (readers skip such entries by their own size).",
        "uint32_t ui_wire_value_kind_words(uint8_t kind);",
        "// The size of an entry holding this value, in words, header included (strings vary).",
        "uint32_t ui_wire_style_value_words(const ui_value *v);",
        "// Writes an entry: its header (property, kind, size) and the value. Returns the end.",
        "uint8_t *ui_wire_style_entry_put(uint8_t *p, uint16_t property, const ui_value *v);",
        "// Reads the value of an entry of a known kind; false if the entry is too short for it.",
        "// A string's bytes stay in the buffer.",
        "bool ui_wire_style_value_read(const uint8_t *entry, ui_value *out);",
        "// True for a property (or the transition of one) this version knows.",
        "bool ui_wire_style_prop_known(uint16_t property);",
        "// True if a declaration of `property` with this value is valid: the property accepts the",
        "// kind and the value is in range. Token references are accepted for every value property",
        "// (their value is checked when resolved). `override` allows UI_VALUE_UNSET.",
        "bool ui_wire_style_value_valid(uint16_t property, const ui_value *v, bool override);",
        "// True if a theme token may hold this value.",
        "bool ui_wire_style_token_value_valid(const ui_value *v);",
        "// A string value of 1 to `max` bytes of UTF-8 without NUL.",
        "bool ui_wire_style_string_valid(const ui_value *v, uint32_t max);",
        "",
    ]


# ---- Codec source ---------------------------------------------------------------------------


def gen_c(s: Schema) -> str:
    out = [BANNER.rstrip(), '#include "wire/gen/wire_gen.h"', "", "#include <math.h>", "#include <string.h>",
           "", '#include "unicode/utf8.h"', ""]
    out += enum_functions(s)
    for r in s.messages():
        if r.kind == "command" and has_checks(r):
            out += check_function(s, r)
        out += put_function(s, r)
    out += framing(s)
    out += style_functions(s)
    return "\n".join(out)


def enum_functions(s: Schema) -> list[str]:
    out = []
    for e in s.enums.values():
        if any(v.components for v in e.values):
            out.append(f"uint32_t {e.c_type}_components({e.c_type} {e.name}) {{")
            out.append(f"    switch ({e.name}) {{")
            for v in e.values:
                out.append(f"    case {enum_const(e, v.name)}: return {v.components or 0};")
            out.append("    }")
            out.append("    return 0;")
            out.append("}")
            out.append("")
        if any(v.min is not None for v in e.values):
            out.append(f"static float {e.name}_min(uint32_t v) {{")
            out.append("    switch (v) {")
            for v in e.values:
                if v.min is not None:
                    out.append(f"    case {enum_const(e, v.name)}: return {num(v.min)};")
            out.append("    default: return -INFINITY;")
            out.append("    }")
            out.append("}")
            out.append("")
    for e in used_known_enums(s):
        out.append(f"static bool {e.name}_known(uint32_t v) {{")
        if e.bitmask:
            mask = 0
            for v in e.values:
                mask |= v.value
            out.append(f"    return !(v & ~{mask:#x}u);")
        else:
            out.append("    switch (v) {")
            for v in e.values:
                out.append(f"    case {v.value}:")
            out.append("        return true;")
            out.append("    default: return false;")
            out.append("    }")
        out.append("}")
        out.append("")
    return out


def used_known_enums(s: Schema) -> list[Enum]:
    seen = []
    for r in s.commands:
        for f in r.fields:
            if any(c.kind == "known" for c in f.checks) and f.enum not in seen:
                seen.append(f.enum)
    return seen


def float_conds(x: str, checks: list[Check], r: Record | None = None) -> list[str]:
    conds = []
    for c in checks:
        if c.kind == "finite":
            conds.append(f"isfinite({x})")
        elif c.kind == "whole":
            conds.append(f"{x} == floorf({x})")
        elif c.kind == "nonzero":
            conds.append(f"{x} != 0")
        elif c.kind == "range":
            conds += range_conds(x, c, True)
        elif c.kind == "min_of":
            e = r.field(c.ref).enum
            conds.append(f"{x} >= {e.name}_min(v->{c.ref})")
    return conds


def range_conds(x: str, c: Check, is_float: bool) -> list[str]:
    lit = num if is_float else (lambda v: f"{int(v)}")
    out = []
    if c.lo is not None:
        out.append(f"{x} {'>' if c.lo_open else '>='} {lit(c.lo)}")
    if c.hi is not None:
        out.append(f"{x} {'<' if c.hi_open else '<='} {lit(c.hi)}")
    return out


def check_function(s: Schema, r: Record) -> list[str]:
    n = cname(r)
    out = [f"const char *{n}_check(const {n} *v{check_params(r)}) {{"]
    for f in r.fields:
        conds = []
        x = f"v->{f.name}"
        is_float = f.type.base == "f32"
        for c in f.checks:
            if c.kind == "known":
                conds.append(f"{f.enum.name}_known({x})")
            elif c.kind == "components_of":
                ref = r.field(c.ref)
                conds.append(f"{x} != 0 && {x} == {ref.enum.c_type}_components(({ref.enum.c_type})v->{c.ref})")
            elif c.kind == "range":
                conds += range_conds(x, c, is_float)
            else:
                conds += float_conds(x, [c], r)
        if conds:
            out.append(f"    if (!({' && '.join(conds)})) return \"{f.name}\";")
    for t in check_tails(r):
        count = f"v->{t.count_field}"
        if t.kind == "bytes":
            for c in t.checks:
                if c.kind == "utf8":
                    out.append(f"    if (!ui_utf8_valid({t.name}, {count})) return \"{t.name}\";")
                elif c.kind == "no_nul":
                    out.append(f"    if ({count} && memchr({t.name}, 0, {count})) return \"{t.name}\";")
            continue
        conds = float_conds(f"{t.name}[i]", t.checks, r) if t.elem == "f32" else \
            [f"{t.name}[i] != 0" for c in t.checks if c.kind == "nonzero"]
        out.append(f"    for (uint32_t i = 0; i < {count}; i++)")
        out.append(f"        if (!({' && '.join(conds)})) return \"{t.name}\";")
    out.append("    return NULL;")
    out.append("}")
    out.append("")
    return out


def put_function(s: Schema, r: Record) -> list[str]:
    n = cname(r)
    opc = enum_const(s.enums["op" if r.kind == "command" else "event_type"], r.name)
    out = [f"ui_result {n}_put(ui_wire_buf *b, const {n} *v{put_params(s, r)}) {{"]
    terms = [const(r, "SIZE")]
    for ti in r.tail:
        if ti.kind == "bytes" and ti.multiple > 1:
            out.append(f"    if (v->{ti.count_field} % {ti.multiple}) return UI_ERR_INVALID_ARGUMENT;")
        if ti.kind in ("single",) or (ti.record and ti.record.size_field):
            out.append(f"    if ({ti.name}_bytes % 4) return UI_ERR_INVALID_ARGUMENT;")
            terms.append(f"(uint64_t){ti.name}_bytes")
        else:
            step = tail_step(s, r, ti, "v->", None)
            terms.append(f"(uint64_t)({step})")
    out.append(f"    uint64_t size = {' + '.join(terms)};")
    out.append("    if (size > UI_WIRE_MAX_PAYLOAD) return UI_ERR_INVALID_ARGUMENT;")
    out.append(f"    uint8_t *p = ui_wire_buf_op(b, {opc}, (uint32_t)size);")
    out.append("    if (!p) return UI_ERR_OUT_OF_MEMORY;")
    if r.tail:
        out.append(f"    p = {n}_write(p, v);")
    else:
        out.append(f"    {n}_write(p, v);")
    for ti in r.tail:
        cnt = f"v->{ti.count_field}" if ti.count_field else ""
        if ti.kind == "bytes":
            out.append(f"    if ({cnt}) memcpy(p, {ti.name}, {cnt});")
            padded = tail_step(s, r, ti, "v->", None)
            if padded != cnt:
                out.append(f"    memset(p + {cnt}, 0, {padded} - {cnt});")
            out.append(f"    p += {padded};")
        elif ti.kind == "array" and ti.record and not ti.record.size_field:
            out.append(f"    for (uint32_t i = 0; i < {cnt}; i++) p = ui_wire_{ti.record.name}_write(p, &{ti.name}[i]);")
        elif ti.kind == "array" and not ti.record:
            st = ti.elem
            out.append(f"    for (uint32_t i = 0; i < {cnt}; i++) p = ui_wire_put_{st}(p, {ti.name}[i]);")
        else:
            out.append(f"    *{ti.name} = p;")
            out.append(f"    p += {ti.name}_bytes;")
    if r.tail:
        out.append("    (void)p;")
    out.append("    return UI_OK;")
    out.append("}")
    out.append("")
    return out


# ---- Framing ---------------------------------------------------------------------------------


def framing(s: Schema) -> list[str]:
    out = []
    for r in s.records.values():
        if r.size_field:
            out += walk_function(s, r)
    for r in s.messages():
        out += frame_function(s, r)
    for kind, group, enum in (("command", s.commands, "op"), ("event", s.events, "event_type")):
        arg = "opcode" if kind == "command" else "type"
        out.append(f"bool ui_wire_{kind}_framed(uint16_t {arg}, const uint8_t *payload, uint32_t size) {{")
        out.append(f"    switch ({arg}) {{")
        for r in group:
            out.append(f"    case {enum_const(s.enums[enum], r.name)}: return frame_{r.kind}_{r.name}(payload, size);")
        out.append(f"    default: return true; // unknown: skipped")
        out.append("    }")
        out.append("}")
        out.append("")
    out += [
        "ui_result ui_wire_validate_commands(const uint8_t *data, size_t size) {",
        "    ui_wire_reader r;",
        "    ui_result res = ui_wire_reader_init(&r, UI_WIRE_MAGIC_CMD, data, size);",
        "    if (res != UI_OK) return res;",
        "    ui_wire_op op;",
        "    while ((res = ui_wire_reader_next(&r, &op)) == UI_OK) {",
        "        if (!ui_wire_command_framed(op.opcode, op.payload, op.payload_size)) return UI_ERR_MALFORMED;",
        "    }",
        "    return res == UI_ERR_END ? UI_OK : res;",
        "}",
        "",
    ]
    return out


def tail_framing(s: Schema, r: Record, p: str, limit: str, hdr: str, indent: str = "    ") -> list[str]:
    """Checks that r's tail fits [off, limit) with `off` already at its start; leaves `off` at its end."""
    out = []
    for ti in r.tail:
        cnt = f"{hdr}.{ti.count_field}" if ti.count_field else ""
        if ti.kind == "bytes":
            if ti.multiple > 1:
                out.append(f"{indent}if ({cnt} % {ti.multiple}) return false;")
            out.append(f"{indent}off += {tail_step(s, r, ti, hdr + '.', None)};")
        elif ti.kind == "array" and ti.record and ti.record.size_field:
            out.append(f"{indent}if (off > {limit}) return false;")
            out.append(f"{indent}uint32_t {ti.name}_end;")
            out.append(f"{indent}if (!walk_{ti.record.name}({p} + off, (uint32_t)({limit} - off), {cnt}, &{ti.name}_end)) return false;")
            out.append(f"{indent}off += {ti.name}_end;")
        elif ti.kind == "array":
            sf = stride_field(r, ti)
            size = f"{ti.name}_stride" if sf else (const(ti.record, "SIZE") if ti.record else str(SCALARS[ti.elem]))
            out.append(f"{indent}off += (uint64_t){cnt} * {size};")
        elif ti.kind == "single":
            out.append(f"{indent}if (off > {limit}) return false;")
            out.append(f"{indent}uint32_t {ti.name}_end;")
            out.append(f"{indent}if (!walk_{ti.record.name}({p} + off, (uint32_t)({limit} - off), 1, &{ti.name}_end)) return false;")
            out.append(f"{indent}off += {ti.name}_end;")
        # union: the value's own size is checked when it is read
    return out


def header_checks(r: Record, p: str, limit: str, indent: str) -> list[str]:
    out = []
    n = cname(r)
    if r.header_field:
        out.append(f"{indent}uint32_t header = {n}_header_size({p});")
        out.append(f"{indent}if (header < {const(r, 'ORIGINAL')} || header % 4 || header > {limit}) return false;")
    else:
        out.append(f"{indent}uint32_t header = {const(r, 'ORIGINAL')};")
    for f in r.fields:
        if f.assign == "stride":
            ti = r.tail_item(f.assign_ref)
            out.append(f"{indent}uint32_t {ti.name}_stride = {n}_{ti.name}_stride({p});")
            out.append(f"{indent}if ({ti.name}_stride < {const(ti.record, 'ORIGINAL')} || {ti.name}_stride % 4) return false;")
    return out


def walk_function(s: Schema, r: Record) -> list[str]:
    n = cname(r)
    out = [f"// Walks `count` {r.name} records in `bytes`: each must hold its fixed part and fit.",
           f"static bool walk_{r.name}(const uint8_t *p, uint32_t bytes, uint32_t count, uint32_t *end) {{",
           "    uint32_t at = 0;",
           "    for (uint32_t i = 0; i < count; i++) {",
           f"        if (bytes - at < {const(r, 'ORIGINAL')}) return false;",
           "        const uint8_t *q = p + at;",
           f"        uint32_t size = {n}_size(q);",
           f"        if (size < {const(r, 'ORIGINAL')} || size % 4 || size > bytes - at) return false;"]
    nested = [ti for ti in r.tail if ti.kind != "union"]
    if nested:
        out += header_checks(r, "q", "size", "        ")
        out.append(f"        {n} h;")
        out.append(f"        {n}_read(q, header < {const(r, 'SIZE')} ? header : {const(r, 'SIZE')}, &h);")
        out.append("        uint64_t off = header;")
        out += tail_framing(s, r, "q", "size", "h", "        ")
        out.append("        if (off > size) return false;")
    out += ["        at += size;", "    }", "    *end = at;", "    return true;", "}", ""]
    return out


def frame_function(s: Schema, r: Record) -> list[str]:
    n = cname(r)
    out = [f"static bool frame_{r.kind}_{r.name}(const uint8_t *p, uint32_t size) {{",
           f"    if (size < {const(r, 'ORIGINAL')}) return false;"]
    if r.tail:
        out += header_checks(r, "p", "size", "    ")
        out.append(f"    {n} h;")
        out.append(f"    {n}_read(p, header < {const(r, 'SIZE')} ? header : {const(r, 'SIZE')}, &h);")
        out.append("    uint64_t off = header;")
        out += tail_framing(s, r, "p", "size", "h")
        out.append("    return off <= size;")
    else:
        out.append("    (void)p;")
        out.append("    return true;")
    out.append("}")
    out.append("")
    return out


# ---- Style values ------------------------------------------------------------------------------


def kind_const(s: Schema, kind: str) -> str:
    return enum_const(s.enums["value_kind"], kind)


def variant_words(s: Schema, kind: str) -> int:
    v = s.unions["style_value"].variant(kind)
    if not v:
        return 1
    size = 0
    for f in v.fields:
        size += 2 if f.type.base == "str16" else f.size
    return 1 + (size + 3) // 4


def style_functions(s: Schema) -> list[str]:
    if not s.style_props:
        return []
    u = s.unions["style_value"]
    kinds = s.enums["value_kind"]
    out = ["uint32_t ui_wire_value_kind_words(uint8_t kind) {", "    switch (kind) {"]
    by_words: dict[int, list[str]] = {}
    for v in kinds.values:
        by_words.setdefault(variant_words(s, v.name), []).append(v.name)
    for words, names in sorted(by_words.items()):
        for name in names:
            out.append(f"    case {kind_const(s, name)}:")
        out[-1] += f" return {words};"
    out += ["    default: return 0;", "    }", "}", ""]

    # Words of a value (strings vary).
    out.append("uint32_t ui_wire_style_value_words(const ui_value *v) {")
    for var in u.variants:
        for f in var.fields:
            if f.type.base == "str16":
                out.append(f"    if (v->kind == {kind_const(s, var.kind)}) return 1 + (2 + v->{f.name}.length + 3) / 4;")
    out.append("    return ui_wire_value_kind_words((uint8_t)v->kind);")
    out.append("}")
    out.append("")

    # Writing.
    entry = s.records["style_entry"]
    out.append("uint8_t *ui_wire_style_entry_put(uint8_t *p, uint16_t property, const ui_value *v) {")
    out.append("    uint32_t words = ui_wire_style_value_words(v);")
    fields = {f.assign or f.name: f for f in entry.fields}
    out.append(f"    p = ui_wire_style_entry_write(p, &(ui_wire_style_entry){{.{entry.fields[0].name} = property, "
               f".{entry.fields[1].name} = (uint8_t)v->kind, .{fields['words'].name} = (uint8_t)words}});")
    out.append("    switch (v->kind) {")
    for var in u.variants:
        out.append(f"    case {kind_const(s, var.kind)}:")
        for f in var.fields:
            m = f"v->{f.name}"
            if f.type.base == "str16":
                out.append(f"        p = ui_wire_put_u16(p, (uint16_t){m}.length);")
                out.append(f"        memcpy(p, {m}.bytes, {m}.length);")
                out.append(f"        memset(p + {m}.length, 0, (2 + {m}.length + 3) / 4 * 4 - 2 - {m}.length);")
                out.append(f"        return p + (2 + {m}.length + 3) / 4 * 4 - 2;")
            elif f.type.count > 1:
                out.append(f"        for (int i = 0; i < {f.type.count}; i++) p = ui_wire_put_{f.type.base}(p, {m}[i]);")
            else:
                out.append(f"        p = ui_wire_put_{f.type.base}(p, {m});")
        if not any(f.type.base == "str16" for f in var.fields):
            out.append("        return p;")
    out.append("    default: return p;")
    out.append("    }")
    out.append("}")
    out.append("")

    # Reading.
    hdr = entry.size
    out.append("bool ui_wire_style_value_read(const uint8_t *e, ui_value *v) {")
    out.append(f"    uint8_t kind = e[{entry.fields[1].offset}], words = e[{fields['words'].offset}];")
    out.append("    if (words < ui_wire_value_kind_words(kind)) return false;")
    out.append(f"    const uint8_t *p = e + {hdr};")
    out.append("    *v = (ui_value){.kind = (ui_value_kind)kind};")
    out.append("    switch (kind) {")
    for var in u.variants:
        out.append(f"    case {kind_const(s, var.kind)}:")
        off = 0
        for f in var.fields:
            m = f"v->{f.name}"
            if f.type.base == "str16":
                out.append(f"        {m}.length = ui_wire_get_u16(p + {off});")
                out.append(f"        {m}.bytes = (const char *)p + {off + 2}; // stays in the buffer")
                out.append(f"        if ({off + 2}u + {m}.length > (words - 1u) * 4) return false;")
            elif f.type.count > 1:
                out.append(f"        for (int i = 0; i < {f.type.count}; i++) {m}[i] = ui_wire_get_{f.type.base}(p + {off} + 4 * i);")
                off += f.size
            else:
                out.append(f"        {m} = ui_wire_get_{f.type.base}(p + {off});")
                off += f.size
        out.append("        break;")
    out.append("    default: break;")
    out.append("    }")
    out.append("    return true;")
    out.append("}")
    out.append("")

    # Strings.
    sv = u.variant("string").fields[0]
    out.append("bool ui_wire_style_string_valid(const ui_value *v, uint32_t max) {")
    out.append(f"    return v->kind == {kind_const(s, 'string')} && v->{sv.name}.length && v->{sv.name}.length <= max &&")
    out.append(f"           v->{sv.name}.bytes && !memchr(v->{sv.name}.bytes, 0, v->{sv.name}.length) &&")
    out.append(f"           ui_utf8_valid((const uint8_t *)v->{sv.name}.bytes, v->{sv.name}.length);")
    out.append("}")
    out.append("")
    out.append("static bool finite4(const float *c) {")
    out.append("    return isfinite(c[0]) && isfinite(c[1]) && isfinite(c[2]) && isfinite(c[3]);")
    out.append("}")
    out.append("")

    # Properties.
    c_type, prefix = s.style_c
    out.append("bool ui_wire_style_prop_known(uint16_t property) {")
    out.append("    if (property & 0x8000u) {")
    out.append("        switch (property & 0x7FFFu) {")
    for p in s.style_props:
        if "transition" in p.flags:
            out.append(f"        case {prefix}{upper(p.name)}:")
    out.append("            return true;")
    out.append("        default: return false;")
    out.append("        }")
    out.append("    }")
    out.append("    switch (property) {")
    for p in s.style_props:
        if p.declarable:
            out.append(f"    case {prefix}{upper(p.name)}:")
    out.append("        return true;")
    out.append("    default: return false;")
    out.append("    }")
    out.append("}")
    out.append("")

    smax = string_max(s)
    out.append("bool ui_wire_style_value_valid(uint16_t property, const ui_value *v, bool override) {")
    out.append("    if (!ui_wire_style_prop_known(property)) return false;")
    out.append(f"    if (v->kind == {kind_const(s, 'unset')}) return override;")
    out.append("    // Every declarable property and transition takes inherit and initial (CSS-wide keywords).")
    out.append(f"    if (v->kind == {kind_const(s, 'inherit')} || v->kind == {kind_const(s, 'initial')}) return true;")
    out.append(f"    if (property & 0x8000u) return {alternatives(s, s.transition_values, smax)};")
    out.append(f"    if (v->kind == {kind_const(s, 'token')}) return v->token != 0;")
    out.append("    float n = v->number;")
    out.append("    (void)n;")
    out.append("    switch (property) {")
    groups: dict[str, list[str]] = {}
    for p in s.style_props:
        if not p.declarable:
            continue
        groups.setdefault(alternatives(s, p.values, smax), []).append(f"{prefix}{upper(p.name)}")
    for cond, names in groups.items():
        for name in names:
            out.append(f"    case {name}:")
        out.append(f"        return {cond};")
    out.append("    default: return false;")
    out.append("    }")
    out.append("}")
    out.append("")

    out.append("bool ui_wire_style_token_value_valid(const ui_value *v) {")
    out.append(f"    float n = v->number;")
    out.append("    (void)n;")
    out.append(f"    return {alternatives(s, s.token_values, smax)};")
    out.append("}")
    out.append("")
    return out


def alternatives(s: Schema, values: list[ValueSpec], smax: int) -> str:
    conds = []
    u = s.unions["style_value"]
    for v in values:
        k = f"v->kind == {kind_const(s, v.kind)}"
        if v.kind in ("px", "percent", "number"):
            c = [k, "isfinite(n)"]
            if v.check:
                c += range_conds("n", v.check, True)
            if v.whole:
                c.append("n == floorf(n)")
            conds.append("(" + " && ".join(c) + ")")
        elif v.kind == "color":
            conds.append(f"({k} && finite4(v->color))")
        elif v.kind == "keyword":
            if not v.enum:
                conds.append(k)
                continue
            e = s.enums[v.enum]
            names = v.allowed or [x.name for x in e.values]
            mask = 0
            for name in names:
                mask |= 1 << e.value(name).value
            conds.append(f"({k} && v->keyword < 32 && ({mask:#x}u >> v->keyword & 1u))")
        elif v.kind == "string":
            conds.append(f"ui_wire_style_string_valid(v, {v.max_bytes or smax})")
        elif v.kind == "token":
            conds.append(f"({k} && v->token != 0)")
        elif v.kind == "spring":
            var = u.variant("spring")
            c = [k]
            for f in var.fields:
                c += float_conds(f"v->{f.name}", f.checks)
            conds.append("(" + " && ".join(c) + ")")
        else:
            conds.append(f"{k}")
    if len(conds) == 1 and conds[0].startswith("(") and conds[0].endswith(")"):
        return conds[0][1:-1]
    return " ||\n               ".join(conds)
